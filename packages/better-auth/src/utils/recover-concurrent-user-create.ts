import type { GenericEndpointContext } from "@better-auth/core";
import { isAPIError } from "./is-api-error";

/**
 * Reserve an id for a user that is about to be created, so that a failed
 * insert can later be told apart from a failure that happened after our own
 * row was written (for example a `databaseHooks.user.create.after` hook that
 * throws).
 *
 * The id follows the same precedence the adapter uses when it generates one
 * itself: the application's `advanced.database.generateId` strategy first,
 * then the adapter-level `customIdGenerator` (for example MongoDB
 * `ObjectId`s), then the default generator. Returns `undefined` when ids are
 * generated by the database.
 */
export function reserveUserId(ctx: GenericEndpointContext): string | undefined {
	const strategy = ctx.context.options.advanced?.database?.generateId;
	if (
		typeof strategy !== "function" &&
		strategy !== "uuid" &&
		strategy !== false &&
		strategy !== "serial"
	) {
		const customIdGenerator = (
			ctx.context.adapter as {
				options?: {
					adapterConfig?: {
						customIdGenerator?: (props: { model: string }) => string;
					};
				};
			}
		).options?.adapterConfig?.customIdGenerator;
		if (customIdGenerator) {
			return customIdGenerator({ model: "user" });
		}
	}
	const id = ctx.context.generateId({ model: "user" });
	return id === false ? undefined : id;
}

/**
 * Called when `createUser` threw. Returns the user that a concurrent request
 * created for `email`, or `null` when the failure must be rethrown.
 *
 * Recovery is limited to a lost insert race:
 * - If the user found carries the id we reserved, our own insert succeeded and
 *   the error came from later work such as an `after` hook, so it is rethrown.
 * - If ids are database-generated we cannot compare ids, so errors raised by
 *   hooks (`APIError`) are rethrown and only other errors are treated as a
 *   possible unique violation.
 * - A failing lookup never replaces the original error.
 */
export async function findConcurrentlyCreatedUser(
	ctx: GenericEndpointContext,
	email: string,
	reservedId: string | undefined,
	error: unknown,
) {
	if (reservedId === undefined && isAPIError(error)) {
		return null;
	}
	try {
		const found = await ctx.context.internalAdapter.findUserByEmail(email);
		if (!found) {
			return null;
		}
		if (reservedId !== undefined && found.user.id === reservedId) {
			return null;
		}
		return found;
	} catch {
		return null;
	}
}
